import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.preprocessing import MinMaxScaler

print("Libraries imported successfully")
df = pd.read_csv("/content/dynamic_supply_chain_logistics_dataset.csv")
print("Dataset uploaded successfully")
print("First Five Records:")
display(df.head())
print("Dataset shape:", df.shape)
print("Column names:")
print(df.columns.tolist())
print("\nDataset information:")
df.info()
print("\nStatistical Summary:")
display(df.describe())
missing_values = df.isnull().sum()
print("Missing values in each column:")
print(missing_values)
print("\ntotal Missing values:", df.isnull().sum().sum())
duplicates = df.duplicated().sum()
print("Duplicate records:", duplicates)
df = df.drop_duplicates()
print("Dataset after removing duplicates:", df.shape)
df["timestamp"] = pd.to_datetime(
    df["timestamp"], errors = "coerce"
)
print(df.dtypes)
print("\ntimestamp conversion completed!")
numeric_cols = df.select_dtypes(
    include=["number"]
).columns
for col in numeric_cols:
  df[col] = df[col].fillna(df[col].median())
categorical_cols = df.select_dtypes(
    include=["object","string"]
).columns
for col in categorical_cols:
  if df[col].isnull().any():
    df[col] = df[col].fillna(
        df[col].mode()[0]
    )
print("Missing values after cleaning:")
print(df.isnull().sum().sum())

# Corrected selection type from "Number" to "number"
numeric_cols = df.select_dtypes(
    include=["number"]
).columns
outlier_summary = []
for col in numeric_cols:
  # Corrected "qunatile" to "quantile"
  Q1 = df[col].quantile(0.25)
  Q3 = df[col].quantile(0.75)
  IQR = Q3 - Q1
  lower_bound = Q1 - 1.5 * IQR
  upper_bound = Q3 + 1.5 * IQR
  outliers = df[(df[col] < lower_bound) | (df[col] > upper_bound)]
  outlier_summary.append({
      "Column": col,
      "Outlier Count": len(outliers),
      "Lower Bound": lower_bound,
      "Upper Bound": upper_bound
  })

outlier_df = pd.DataFrame(outlier_summary)
display(outlier_df)
plt.figure(figsize=(10,5))
plt.boxplot(
    df["shipping_costs"].dropna(),
    vert=False,
)
plt.title("Shipping Cost Outlier Detection")
plt.xlabel("Shipping Cost")
plt.show()

# Corrected "Number" to "number"
numeric_cols = df.select_dtypes(
    include=["number"]
).columns

# Corrected "Scaler" to lowercase "scaler" to match its usage below
scaler = MinMaxScaler()
df_normalized = df.copy()
df_normalized[numeric_cols] = scaler.fit_transform(
    df[numeric_cols]
)
print("Normalization completed successfully!")
display(df_normalized.head())
print("Final Data Quality Report")
print("\nDataset Dimensions:")
print(df.shape)
print("\nMissing Values:")
print(df.isnull().sum().sum())
print("\nDuplicate Records:")
print(df.duplicated().sum())
print("\nData Types:")
print(df.dtypes)
print("\nFinal Dataset Preview:")
display(df.head())
df.to_csv(
    "cleaned_logistics_dataset.csv",
    index=False
)
# Corrected df.normalised to df_normalized
df_normalized.to_csv(
    "normalized_logistics_dataset.csv",
    index=False
)
